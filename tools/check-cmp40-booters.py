#!/usr/bin/env python3
"""Verify the signed Booter archive used by the 615.78.08 CMP40 patch.

Reads official NVIDIA source archives; never accesses a GPU. Optionally
regenerates the embedded 610.57.04 archive header while preserving firmware data.
"""
import argparse
import hashlib
from pathlib import Path
import re
import struct
import tarfile
import zlib

ARCHIVES = {
    "610.57.04": "619d7b5ce1f79c3211afdbf87d02b2174d268b10d005c5b8f994be22299be681",
    "615.78.08": "eac0ecd52facab28ad2963cf7e03ae8d2289d596ad590c703b5f72d65899e2bf",
}
LABELS = ["IMAGE_DBG", "HEADER_DBG", "IMAGE_PROD", "HEADER_PROD", "SIG_DBG",
          "SIG_PROD", "PATCH_LOC", "PATCH_SIG", "PATCH_META", "NUM_SIGS"]
SOURCE = "src/nvidia/generated/g_bindata_kgspGetBinArchiveBooterLoadUcode_TU102.c"
HEADER = "src/nvidia/src/kernel/gpu/gsp/cmp40_booter_load_610.h"


def read_archive(path, version):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != ARCHIVES[version]:
        raise ValueError(f"Incorrect {version} archive SHA256: {digest}")
    with tarfile.open(path) as tar:
        source = tar.extractfile(f"open-gpu-kernel-modules-{version}/{SOURCE}").read().decode()
    entries = {}
    for label in LABELS:
        match = re.search(r"BINDATA_LABEL_" + label + r"_data\[\].*?\{(.*?)\}", source, re.S)
        comment = source[source.rfind("// FUNCTION:", 0, match.start()):match.start()]
        body = match[1]
        if "ULL" in body:
            raw = b"".join(struct.pack("<Q", int(x, 16))
                           for x in re.findall(r"0x([0-9a-f]+)ULL", body))
        else:
            raw = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", body))
        actual = int(re.search(r"// DATA SIZE \(bytes\): (\d+)", comment)[1])
        compressed = "// COMPRESSION: YES" in comment
        size = int(re.search(r"// COMPRESSED SIZE \(bytes\): (\d+)", comment)[1]) if compressed else actual
        raw = raw[:size]
        if compressed:
            decoder = zlib.decompressobj(-15)
            blob = decoder.decompress(raw) + decoder.flush()
            crc, isize = struct.unpack("<II", decoder.unused_data)
            if not decoder.eof or crc != zlib.crc32(blob) or isize != len(blob):
                raise ValueError(f"Invalid compressed {version}/{label}")
        else:
            blob = raw
        if len(blob) != actual:
            raise ValueError(f"Invalid size for {version}/{label}")
        entries[label] = (raw, blob, compressed)
    return entries


def generate_header(entries):
    result = """/*
 * SPDX-FileCopyrightText: Copyright (c) 2016-2025 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
 * SPDX-License-Identifier: MIT
 *
 * TU102 Booter Load from the official 610.57.04 source archive.
 * Compressed data and all signature metadata are preserved byte-for-byte.
 * Only the CMP40 unlock transaction uses this archive. The GSP launch,
 * suspend/resume and unload paths use the driver's native Booter archive.
 *
 * Source archive SHA256:
 * 619d7b5ce1f79c3211afdbf87d02b2174d268b10d005c5b8f994be22299be681
 * Generated by tools/check-cmp40-booters.py --generate-header.
 */
#ifndef CMP40_BOOTER_LOAD_610_H
#define CMP40_BOOTER_LOAD_610_H

#include "../../core/bin_data_pvt.h"

"""
    for label, (raw, blob, compressed) in entries.items():
        name = "cmp40Booter610_" + label
        padded = raw + b"\0" * (-len(raw) % 8)
        words = struct.unpack("<" + "Q" * (len(padded) // 8), padded)
        result += f"static const NV_DECLARE_ALIGNED(NvU64, 8) {name}_data[] =\n{{\n"
        for i in range(0, len(words), 2):
            result += "    " + ", ".join(f"0x{x:016x}ULL" for x in words[i:i + 2]) + ",\n"
        result += "};\n"
        flag = "BINDATA_FLAG_COMPRESSED" if compressed else "0"
        result += f"static const BINDATA_STORAGE_PVT {name}_storage =\n{{\n"
        result += f"    {len(blob)}, {len(raw)}, {name}_data, {flag}, 0\n}};\n\n"
    result += "static const BINDATA_ARCHIVE cmp40Booter610Archive =\n{\n    10,\n    {\n"
    for label in LABELS:
        result += f"        {{ BINDATA_LABEL_{label}, (const PBINDATA_STORAGE)&cmp40Booter610_{label}_storage }},\n"
    return result + "    }\n};\n\n#endif // CMP40_BOOTER_LOAD_610_H\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--legacy-source", type=Path, required=True)
    parser.add_argument("--native-source", type=Path, required=True)
    parser.add_argument("--tree", type=Path, help="Patched 615.78.08 source tree to verify")
    parser.add_argument("--generate-header", type=Path, help="Write the generated header here")
    args = parser.parse_args()
    legacy = read_archive(args.legacy_source, "610.57.04")
    native = read_archive(args.native_source, "615.78.08")
    for version, entries, code_size in [("610.57.04", legacy, 0x8400), ("615.78.08", native, 0x8600)]:
        for variant in ["DBG", "PROD"]:
            header = struct.unpack("<9I", entries["HEADER_" + variant][1])
            assert header == (0, 0x100, code_size + 0x100, 0x6200, 1, 0x100, code_size, 0x100, 0)
            image = entries["IMAGE_" + variant][1]
            assert len(image) == header[2] + header[3]
            sig = entries["SIG_" + variant][1]
            count = struct.unpack("<I", entries["NUM_SIGS"][1])[0]
            patch_loc = struct.unpack("<I", entries["PATCH_LOC"][1])[0]
            assert count > 0 and len(sig) % count == 0
            assert header[2] <= patch_loc < len(image) - len(sig) // count
            print(f"{version} {variant}: size={len(image):#x} SHA256={hashlib.sha256(image).hexdigest()}")
    generated = generate_header(legacy)
    if args.generate_header:
        args.generate_header.write_text(generated)
    if args.tree:
        assert (args.tree / HEADER).read_text() == generated, "Embedded legacy archive differs from official source"
        native_c = (args.tree / SOURCE).read_bytes()
        with tarfile.open(args.native_source) as tar:
            assert native_c == tar.extractfile(f"open-gpu-kernel-modules-615.78.08/{SOURCE}").read(), "Native Booter was modified"
        booter = (args.tree / "src/nvidia/src/kernel/gpu/gsp/arch/turing/kernel_gsp_booter_tu102.c").read_text()
        assert "kgspCmp40AllocateUnlockBooter(pGpu, pKernelGsp, &pUnlockBooter)" in booter
        assert "pGpu, pKernelGsp, pUnlockBooter," in booter
        assert "kgspFreeFlcnUcode(pUnlockBooter);" in booter
        assert "pKernelGsp->pBooterLoadUcode," in booter
        tu102 = (args.tree / "src/nvidia/src/kernel/gpu/gsp/arch/turing/kernel_gsp_tu102.c").read_text()
        free_args = tu102[tu102.index("kgspFreeBootArgs_TU102"):tu102.index("#define INTERRUPT_PROCESSOR_SUSPENDED_VALUE")]
        prepare = tu102[tu102.index("kgspPrepareForBootstrap_TU102"):tu102.index("_kgspGetBooterLoadArgs")]
        assert "portMemFree(pKernelGsp->pStockSignatureData)" in free_args
        assert "portMemFree(pKernelGsp->pStockSignatureData)" not in prepare
        gsp = (args.tree / "src/nvidia/src/kernel/gpu/gsp/kernel_gsp.c").read_text()
        assert "BOUNDED_INIT_TIMEOUT_CONTINUE" not in gsp, "GMCAPI timeout must stop initialization"
        print("PASS: legacy archive and signatures match; native Booter unchanged; unlock allocation freed; stock signature lifetime correct")


if __name__ == "__main__":
    main()
